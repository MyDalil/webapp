/**
 * Langues du site : français (par défaut), anglais (/en), arabe (/ar, de droite à gauche).
 * Règle : noms propres, adresses et horaires jamais traduits (affichés comme publiés par leur source).
 * Traductions relues à la main ; une clé absente retombe sur le français.
 */
export type Lang = 'fr' | 'en' | 'ar'
type T = { en: string; ar: string }

export const langOf = (path: string): Lang =>
  path === '/ar' || path.startsWith('/ar/') ? 'ar' : path === '/en' || path.startsWith('/en/') ? 'en' : 'fr'
export const isRtl = (l: Lang) => l === 'ar'
export const homeHref = (l: Lang) => (l === 'fr' ? '/' : `/${l}`)
export const tr = (fr: string, d: Record<string, T>, l: Lang) => (l === 'fr' ? fr : (d[fr]?.[l] ?? fr))

/** Pluriel simple : n + mot (fr/en), formes arabes 1 / 2 / 3-10 / 11+. */
export function count(n: number, l: Lang, w: { fr: [string, string]; en: [string, string]; ar: [string, string, string, string] }) {
  if (l === 'ar') return n === 1 ? w.ar[0] : n === 2 ? w.ar[1] : n >= 3 && n <= 10 ? `${n} ${w.ar[2]}` : `${n} ${w.ar[3]}`
  const [one, many] = w[l]
  return `${n} ${n > 1 ? many : one}`
}

