/** Textes fixes du bot visiteur (FR par défaut, EN et AR selon la langue de l’appareil). Aucun texte généré par une IA. */
export type BotLang = 'fr' | 'en' | 'ar'

/** Langue Telegram (language_code « ar », « en-US »…) ou texte en lettres arabes → langue du bot ; français par défaut. */
export function botLang(code?: string | null, text?: string): BotLang {
  const c = (code ?? '').toLowerCase()
  if (c.startsWith('ar')) return 'ar'
  if (c.startsWith('en')) return 'en'
  if (!c && text && /[؀-ۿ]/.test(text)) return 'ar'
  return 'fr'
}

